package dev.reflash.core;

import java.util.Locale;

/**
 * Advisory preset targets only. Momenton on VulkanMod cannot render above the
 * current window size. Selecting these does NOT configure its export job.
 */
public enum ExportPreset {
    HD60("HD60", "1080P / 60", 1920, 1080, 60),
    HD120("HD120", "1080P / 120", 1920, 1080, 120),
    QHD60("QHD60", "1440P / 60", 2560, 1440, 60),
    QHD120("QHD120", "1440P / 120", 2560, 1440, 120),
    UHD60("UHD60", "4K / 60", 3840, 2160, 60);

    private final String id;
    private final String label;
    private final int width;
    private final int height;
    private final int fps;

    ExportPreset(String id, String label, int width, int height, int fps) {
        this.id = id;
        this.label = label;
        this.width = width;
        this.height = height;
        this.fps = fps;
    }

    public String id() { return id; }
    public String label() { return label; }
    public int width() { return width; }
    public int height() { return height; }
    public int fps() { return fps; }
    public String detail() { return String.format(Locale.ROOT, "%d x %d @ %d FPS", width, height, fps); }
    /** Number of source pixels generated by an offline render per second, before SSAA. */
    public long pixelsPerSecond() { return Math.multiplyExact(Math.multiplyExact((long)width, height), fps); }
    /** For estimating storage at a chosen bitrate; includes video only, not audio/container overhead. */
    public long estimatedVideoBytes(long durationSeconds, long bitrateMegabitsPerSecond) {
        if (durationSeconds < 0 || bitrateMegabitsPerSecond < 0)
            throw new IllegalArgumentException("Duration and bitrate must not be negative");
        return Math.multiplyExact(Math.multiplyExact(durationSeconds, bitrateMegabitsPerSecond), 1_000_000L) / 8L;
    }
    public long frameCount(long durationSeconds) {
        if (durationSeconds < 0) throw new IllegalArgumentException("durationSeconds must not be negative");
        return Math.multiplyExact(durationSeconds, fps);
    }
    public ExportPreset next() { return values()[(ordinal() + 1) % values().length]; }
    public static ExportPreset fromId(String id) {
        if (id != null) for (ExportPreset p : values()) if (p.id.equals(id)) return p;
        return HD60;
    }
}
